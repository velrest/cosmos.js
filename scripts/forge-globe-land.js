// Run once: node scripts/forge-globe-land.js
// Downloads Natural Earth's public domain land outlines and writes demo/land.js.
import { writeFileSync } from "node:fs";

const SOURCE =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson";
const OUTPUT = new URL("../demo/land.js", import.meta.url);

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`Download failed: ${response.status}`);
const { features } = await response.json();

const rings = [];
for (const { geometry } of features) {
  const polygons = geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  for (const polygon of polygons) {
    for (const ring of polygon) {
      rings.push(ring.map(([lon, lat]) => [Number(lon.toFixed(1)), Number(lat.toFixed(1))]));
    }
  }
}

writeFileSync(
  OUTPUT,
  "// Generated by scripts/forge-globe-land.js from Natural Earth (public domain). See NOTICE.md.\n" +
    "// Each ring is a list of [longitude, latitude] points.\n" +
    `export const LAND_RINGS = ${JSON.stringify(rings)};\n`,
);
console.log(`Wrote ${rings.length} rings`);
