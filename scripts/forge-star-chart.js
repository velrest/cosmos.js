// Run once: node scripts/forge-star-chart.js
// Downloads the HYG catalog and writes src/data/star-chart-data.js.
import { mkdirSync, writeFileSync } from "node:fs";

const SOURCE =
  "https://raw.githubusercontent.com/astronexus/HYG-Database/main/hyg/CURRENT/hygdata_v41.csv";
const OUTPUT = new URL("../src/data/star-chart-data.js", import.meta.url);
const LY_PER_PARSEC = 3.26156;
const MAX_MAGNITUDE = 6;

function parseCsvLine(line) {
  const cells = [];
  let cell = "";
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const char = line[i];
    if (quoted) {
      if (char === '"' && line[i + 1] === '"') {
        cell += '"';
        i++;
      } else if (char === '"') quoted = false;
      else cell += char;
    } else if (char === '"') quoted = true;
    else if (char === ",") {
      cells.push(cell);
      cell = "";
    } else cell += char;
  }
  cells.push(cell);
  return cells;
}

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`Download failed: ${response.status}`);
const [header, ...lines] = (await response.text()).trim().split(/\r?\n/);
const columns = parseCsvLine(header);
const column = (name) => columns.indexOf(name);
const [id, proper, ra, dec, dist, mag, con] = ["id", "proper", "ra", "dec", "dist", "mag", "con"].map(column);

const stars = [];
for (const line of lines) {
  const row = parseCsvLine(line);
  if (row[proper] === "Sol") continue;
  const magnitude = Number(row[mag]);
  if (magnitude > MAX_MAGNITUDE && row[proper] !== "Proxima Centauri") continue;
  stars.push([
    row[proper] || `HYG ${row[id]}`,
    Number((Number(row[ra]) * 15).toFixed(4)),
    Number(Number(row[dec]).toFixed(4)),
    magnitude,
    Number((Number(row[dist]) * LY_PER_PARSEC).toFixed(2)),
    row[con],
  ]);
}

mkdirSync(new URL(".", OUTPUT), { recursive: true });
writeFileSync(
  OUTPUT,
  "// Generated by scripts/forge-star-chart.js. Derived from the HYG Database, CC BY-SA 4.0. See NOTICE.md.\n" +
    "// Each row: [name, ra degrees, dec degrees, magnitude, light years, constellation code]\n" +
    `export const STAR_ROWS = ${JSON.stringify(stars)};\n`,
);
console.log(`Wrote ${stars.length} stars, ${stars.filter((s) => s[0].startsWith("HYG ")).length} unnamed`);
